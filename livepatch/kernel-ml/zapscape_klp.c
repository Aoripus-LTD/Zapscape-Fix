/*
 * zapscape_klp.c - CVE-2026-64561 (Zapscape) live patch for kernel-ml 7.1.3
 *
 * Replaces the four KVM page-fault handlers with the upstream-fixed
 * versions (equivalent of mainline commit 2abd5287f083):
 *   direct_page_fault / paging64_page_fault / paging32_page_fault / ept_page_fault
 *
 * The stale-root check (is_page_fault_stale) is moved AFTER
 * make_mmu_pages_available(); if reclaim zapped the in-use root, the fault
 * returns RET_PF_RETRY and restarts on a fresh root - no invalid shadow
 * children are ever created.
 *
 * Built with the in-kernel KLP toolchain (objtool klp-convert,
 * CONFIG_KLP_BUILD=y) - no kpatch needed. Relocations for kvm.ko internal
 * symbols are generated automatically at build time.
 *
 * Copyright (C) 2026 Aoripus (Beijing) Technology Co., Ltd.
 */
